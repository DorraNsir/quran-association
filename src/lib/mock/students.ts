const prefixes = ["20", "22", "24", "25", "27", "29", "50", "52", "55", "58", "92", "95", "97", "98"]

/** Deterministic 8-digit Tunisian mobile number. */
function phoneFor(seed: number) {
  const prefix = prefixes[seed % prefixes.length]
  const rest = String((seed * 7919 + 104729) % 1_000_000).padStart(6, "0")
  return prefix + rest
}

/**
 * Contact rules mirrored from the association's practice:
 * - under 15: guardian phone only
 * - 15–17: own phone + guardian phone
 * - adults: own phone and CIN
 */
export const students: Student[] = rows.map(
  ([firstName, lastName, gender, dateOfBirth, groupId, registrationDate, status], i) => {
    const age = ageOn(dateOfBirth, MOCK_TODAY)
    return {
      id: `s${i + 1}`,
      firstName,
      lastName,
      gender,
      dateOfBirth,
      phone: age >= 15 ? phoneFor(i * 3 + 1) : undefined,
      guardianPhone: age < 18 ? phoneFor(i * 3 + 2) : undefined,
      cin: age >= 18 ? String(8_000_000 + ((i * 104_729) % 900_000)).padStart(8, "0") : undefined,
      address: streets[i % streets.length],
      registrationDate,
      groupId,
      status,
    }
  }
)
